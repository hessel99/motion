// drag & drop of real files onto the viewport: lottie json, svg, png, .motion
import { chromium } from './pw.mjs';
import { readFileSync } from 'node:fs';
const [,, lottiePath] = process.argv;
const browser = await chromium.launch({ args: ['--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => m.type() === 'error' && !m.text().includes('GL Driver') && errs.push(m.text()));
await page.goto((process.env.URL || 'http://localhost:5173/') + '?blank&nobridge');
await page.waitForFunction(() => window.editor?.renderer);
const drop = (name, type, b64) => page.evaluate(async ([name, type, b64]) => {
  const bin = Uint8Array.from(atob(b64), c => c.charCodeAt(0));
  const file = new File([bin], name, { type });
  const dt = new DataTransfer(); dt.items.add(file);
  const vp = document.querySelector('.viewport');
  vp.dispatchEvent(new DragEvent('drop', { dataTransfer: dt, bubbles: true, cancelable: true }));
  await new Promise(r => setTimeout(r, 1200));
  return { layers: Object.keys(editor.store.project.layers).length, name: editor.store.project.name, assets: Object.keys(editor.store.project.assets).length };
}, [name, type, b64]);
const results = {};
results.lottie = await drop('anim.json', 'application/json', readFileSync(lottiePath).toString('base64'));
results.svg = await drop('logo.svg', 'image/svg+xml', Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect x="10" y="10" width="80" height="80" rx="12" fill="#4c8dff"/></svg>').toString('base64'));
// a real png generated by the browser
const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 64; c.height = 48; const g = c.getContext('2d'); g.fillStyle = '#f0a'; g.fillRect(0, 0, 64, 48); return c.toDataURL('image/png').split(',')[1]; });
results.png = await drop('pic.png', 'image/png', png);
// save + reopen (.motion)
const saved = await page.evaluate(async () => { const { serialize } = await import('/src/app/actions.ts'); return serialize(); });
await page.evaluate(() => editor.load({ version: 1, name: 'empty', comps: { c: { id: 'c', name: 'x', width: 100, height: 100, fps: 30, duration: 1, background: [0, 0, 0, 1], root: [] } }, activeComp: 'c', layers: {}, assets: {} }));
results.motion = await drop('project.motion', 'application/json', Buffer.from(saved).toString('base64'));
results.reopenedIdentical = await page.evaluate(async (saved) => { const { serialize } = await import('/src/app/actions.ts'); return serialize() === saved; }, saved);
console.log(JSON.stringify(results));
console.log(errs.length ? errs.slice(0, 5) : 'no errors');
await browser.close();
